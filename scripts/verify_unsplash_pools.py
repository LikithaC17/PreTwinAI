def check(cid):
    url = f"https://images.unsplash.com/photo-{cid}?w=400&q=80"
    headers = {"User-Agent": "Mozilla/5.0"}
    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=3) as resp:
            return cid, resp.status == 200
    except:
        return cid, False

valid = []
with concurrent.futures.ThreadPoolExecutor(max_workers=20) as ex:
    for cid, ok in ex.map(lambda c: check(c), candidates):
        if ok:
            valid.append(cid)

print(f"Total checked: {len(candidates)}, Valid HTTP 200: {len(valid)}")
with open("data/verified_unsplash_ids.txt", "w") as f:
    f.write("\n".join(valid))
