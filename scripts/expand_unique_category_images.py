def verify_single(pid):
    url = f"https://images.unsplash.com/photo-{pid}?w=400&q=80"
    headers = {"User-Agent": "Mozilla/5.0"}
    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=3) as r:
            return pid, r.status == 200
    except:
        return pid, False

unique_pids = list(dict.fromkeys(SHARED_VERIFIED_PHOTO_IDS))
print(f"Total unique IDs to verify: {len(unique_pids)}")

valid_ids = []
with concurrent.futures.ThreadPoolExecutor(max_workers=15) as ex:
    for pid, ok in ex.map(verify_single, unique_pids):
        if ok:
            valid_ids.append(pid)

print(f"Total verified valid IDs: {len(valid_ids)}")

# Load existing verified JSON
vf_path = "data/verified_category_images.json"
with open(vf_path, "r", encoding="utf-8") as f:
    cat_data = json.load(f)

# Ensure each category has strictly 26 UNIQUE photo URLs (no duplicates within the category)
shared_idx = 0
for cat, urls in cat_data.items():
    unique_urls = list(dict.fromkeys(urls))
    while len(unique_urls) < 26:
        candidate_url = f"https://images.unsplash.com/photo-{valid_ids[shared_idx % len(valid_ids)]}?w=400&q=80"
        shared_idx += 1
        if candidate_url not in unique_urls:
            unique_urls.append(candidate_url)
    cat_data[cat] = unique_urls[:26]
    print(f"Category '{cat}': {len(cat_data[cat])} strictly unique URLs.")

with open(vf_path, "w", encoding="utf-8") as f:
    json.dump(cat_data, f, indent=2)

print("\nSuccessfully updated data/verified_category_images.json with strictly unique 26 URLs per category!")
